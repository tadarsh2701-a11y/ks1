  // Devanagari script family fallback (Maithili, Nepali, Konkani, Dogri can utilize structured Hindi/Marathi contextual translations if topic not individually defined)
  const isDevanagariFamily = ['hi', 'mr', 'mai', 'ne', 'kok', 'doi'].includes(lang);
